import { describe, it, expect } from "vitest";
import {
  isExcludedPath,
  isGeneratedContent,
  filterPaths,
} from "../../src/lib/skill-engine/filters/pathFilter";

describe("pathFilter", () => {
  describe("isExcludedPath", () => {
    it("excludes third-party and vendored directories", () => {
      expect(isExcludedPath("node_modules/lodash/index.js")).toBe(true);
      expect(isExcludedPath("packages/app/node_modules/react/index.js")).toBe(true);
      expect(isExcludedPath("vendor/bundle/ruby.rb")).toBe(true);
      expect(isExcludedPath("third_party/protobuf/wire.cc")).toBe(true);
      expect(isExcludedPath(".yarn/cache/package.zip")).toBe(true);
      expect(isExcludedPath(".pnpm-store/v3/files/foo")).toBe(true);
      expect(isExcludedPath("bower_components/jquery/jquery.js")).toBe(true);
    });

    it("excludes build and cache directories", () => {
      expect(isExcludedPath("dist/bundle.js")).toBe(true);
      expect(isExcludedPath("build/output.js")).toBe(true);
      expect(isExcludedPath("out/main.js")).toBe(true);
      expect(isExcludedPath(".next/server/pages/index.js")).toBe(true);
      expect(isExcludedPath("target/classes/Main.class")).toBe(true);
      expect(isExcludedPath("__pycache__/utils.cpython-310.pyc")).toBe(true);
      expect(isExcludedPath(".venv/lib/python3.10/site-packages/os.py")).toBe(true);
      expect(isExcludedPath("venv/bin/activate")).toBe(true);
      expect(isExcludedPath("coverage/lcov-report/index.html")).toBe(true);
    });

    it("excludes lockfiles", () => {
      expect(isExcludedPath("package-lock.json")).toBe(true);
      expect(isExcludedPath("yarn.lock")).toBe(true);
      expect(isExcludedPath("pnpm-lock.yaml")).toBe(true);
      expect(isExcludedPath("poetry.lock")).toBe(true);
      expect(isExcludedPath("Cargo.lock")).toBe(true);
      expect(isExcludedPath("go.sum")).toBe(true);
      expect(isExcludedPath("composer.lock")).toBe(true);
      expect(isExcludedPath("subproject/Cargo.lock")).toBe(true);
    });

    it("excludes minified, map, snap, asset and binary files", () => {
      expect(isExcludedPath("assets/app.min.js")).toBe(true);
      expect(isExcludedPath("styles/global.min.css")).toBe(true);
      expect(isExcludedPath("dist/app.js.map")).toBe(true);
      expect(isExcludedPath("tests/__snapshots__/index.test.ts.snap")).toBe(true);
      expect(isExcludedPath("public/logo.svg")).toBe(true);
      expect(isExcludedPath("images/photo.png")).toBe(true);
      expect(isExcludedPath("images/avatar.jpg")).toBe(true);
      expect(isExcludedPath("docs/manual.pdf")).toBe(true);
    });

    it("keeps real authored source code", () => {
      expect(isExcludedPath("src/index.ts")).toBe(false);
      expect(isExcludedPath("src/components/Button.tsx")).toBe(false);
      expect(isExcludedPath("backend/main.py")).toBe(false);
      expect(isExcludedPath("src/main/java/com/app/Service.java")).toBe(false);
      expect(isExcludedPath("cmd/server/main.go")).toBe(false);
      expect(isExcludedPath("src/lib.rs")).toBe(false);
      expect(isExcludedPath("Dockerfile")).toBe(false);
      expect(isExcludedPath("package.json")).toBe(false);
    });
  });

  describe("isGeneratedContent", () => {
    it("detects generated markers in headers", () => {
      expect(isGeneratedContent("// @generated\nconst x = 1;")).toBe(true);
      expect(isGeneratedContent("/* Code generated by protoc-gen-go. DO NOT EDIT. */\npackage pb")).toBe(true);
      expect(isGeneratedContent("// DO NOT EDIT THIS FILE DIRECTLY\nexport const v = 2;")).toBe(true);
    });

    it("passes human-authored code", () => {
      expect(isGeneratedContent("import React from 'react';\nexport function App() { return null; }")).toBe(false);
      expect(isGeneratedContent("def calculate_skills(data):\n    return data")).toBe(false);
    });
  });

  describe("filterPaths", () => {
    it("filters a list of paths correctly", () => {
      const input = [
        "src/app.ts",
        "node_modules/foo/bar.js",
        "package-lock.json",
        "src/utils.py",
        "dist/bundle.min.js",
      ];
      expect(filterPaths(input)).toEqual(["src/app.ts", "src/utils.py"]);
    });
  });
});
